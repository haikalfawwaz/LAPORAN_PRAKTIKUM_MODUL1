putaran = 5
jarak = 14
phi = 3.14

r = jarak / (2 * phi * putaran)

print("Diketahui:")
print("Pak Dengklek mengelilingi taman =", putaran, "Putaran")
print("Jarak tempuh Pak Dengklek =", jarak, "Kilometer")
print()
print("Jawaban:")
print("Jari-jari taman yang dikelilingi Pak Dengklek adalah", f"{r:.2f}", "Kilometer")